#!/usr/bin/env python3
"""
Write the stopword list and the boilerplate list as LaTeX tables, for the report.

The lists are read from where the pipeline takes them, so the tables always show what is used:
    stopwords:   preprocessing/05_remove_stopwords.py (NLTK's Swedish list + the words added for this corpus)
    boilerplate: config/boilerplate_phrases.txt (one phrase per line, '# N. Category' headings)

Output: docs/tables/preprocessing_word_lists.tex (read by docs/tables/preprocessing_decisions.tex)

Usage: python analysis/word_lists_latex.py
"""

import importlib.util
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
STOPWORD_SCRIPT = PROJECT_ROOT / 'preprocessing' / '05_remove_stopwords.py'
BOILERPLATE_FILE = PROJECT_ROOT / 'config' / 'boilerplate_phrases.txt'
OUTPUT = PROJECT_ROOT / 'docs' / 'tables' / 'preprocessing_word_lists.tex'

LATEX_SPECIAL = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#', '_': r'\_',
                 '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}


def latex(text):
    return ''.join(LATEX_SPECIAL.get(c, c) for c in text)


def nltk_stopwords():
    """NLTK's Swedish list, from the same data folder as the pipeline (via 05_remove_stopwords.py)."""
    spec = importlib.util.spec_from_file_location('remove_stopwords', STOPWORD_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    full = module.get_swedish_stopwords()
    return set(module.stopwords.words('swedish')), full


def boilerplate_categories(path):
    """[(category, [phrases])] in file order, from the '# N. Category' headings."""
    categories = []
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        heading = re.match(r'#\s*\d+\.\s*(.+)', line)
        if heading:
            categories.append((heading.group(1).strip(), []))
        elif line and not line.startswith('#'):
            if not categories:
                raise ValueError(f"Phrase before the first category heading: {line!r}")
            categories[-1][1].append(line)
    return categories


TABLE_START = r"""{\small
\renewcommand{\arraystretch}{1.3}
\setlength{\LTcapwidth}{\linewidth}
\begin{longtable}{|>{\raggedright\arraybackslash}p{0.24\linewidth}
                  |>{\raggedleft\arraybackslash}p{0.05\linewidth}
                  |>{\raggedright\arraybackslash}p{0.63\linewidth}|}
"""

TABLE_HEAD = r"""\hline
\textbf{%s} & \textbf{Words} & \textbf{%s} \\
\hline
\endfirsthead
\hline
\textbf{%s} & \textbf{Words} & \textbf{%s} \\
\hline
\endhead
\multicolumn{3}{r}{\emph{continued on next page}} \\
\endfoot
\endlastfoot
"""


def stopword_table(nltk_words, full):
    added = full - nltk_words
    lines = [TABLE_START,
             r"\caption{Stopwords (step 05): NLTK's Swedish list and the %d words added for this corpus (%d stopwords in "
             r"all). The added words were chosen by inspecting early models, with their lemma forms, since the text is "
             r"lemmatized. Matched against the lemmatized, lowercased text.}" % (len(added), len(full)),
             r"\label{tab:stopwords} \\",
             TABLE_HEAD % ('Source', 'Stopwords', 'Source', 'Stopwords')]
    for source, words in (('NLTK Swedish list', nltk_words), ('Added for this corpus', added)):
        lines.append(r"%s & %d & %s \\" % (source, len(words), latex(', '.join(sorted(words)))))
        lines.append(r"\hline")
    lines += [r"\end{longtable}", "}"]
    return '\n'.join(lines)


def boilerplate_table(categories):
    total = sum(len(p) for _, p in categories)
    lines = [TABLE_START,
             r"\caption{Parliamentary boilerplate (step 03): %d words and phrases in %d categories, matched against the "
             r"original word forms; a word is removed only if a phrase covers the whole word.}" % (total, len(categories)),
             r"\label{tab:boilerplate} \\",
             TABLE_HEAD % ('Category', 'Words and phrases', 'Category', 'Words and phrases')]
    for category, phrases in categories:
        lines.append(r"%s & %d & %s \\" % (latex(category), len(phrases), latex(', '.join(phrases))))
        lines.append(r"\hline")
    lines += [r"\end{longtable}", "}"]
    return '\n'.join(lines)


def main():
    nltk_words, full = nltk_stopwords()
    text = '\n'.join([
        "% Generated by analysis/word_lists_latex.py from preprocessing/05_remove_stopwords.py and",
        "% config/boilerplate_phrases.txt; do not edit by hand. Requires array and longtable.",
        "",
        stopword_table(nltk_words, full),
        "",
        r"\clearpage",
        "",
        boilerplate_table(boilerplate_categories(BOILERPLATE_FILE)),
        "",
    ])
    OUTPUT.write_text(text, encoding='utf-8')
    print(f"✅ Saved to: {OUTPUT}")


if __name__ == '__main__':
    main()
